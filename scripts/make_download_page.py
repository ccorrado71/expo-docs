#!/usr/bin/env python3
"""Generate docs/download.md with public ownCloud links to the EXPO packages.

For every file in the local packages folder (synced with cnrbox by the ownCloud
desktop client) the script:

  1. checks that the file is already on the server with the same size
     (i.e. the sync client has finished uploading it);
  2. reuses the existing public link of the file, or creates a new one
     (read-only, no password, no expiration);
  3. writes docs/download.md, grouping the files by version and platform.

Credentials are read from ~/.netrc, e.g.:

    machine cnrbox.cnr.it login <username> password <app-password>

Usage:
    python3 scripts/make_download_page.py [--dry-run] [--local-dir DIR] [--output FILE]

With --dry-run no public link is created: existing links are reused and missing
ones are shown as placeholders.
"""

import argparse
import json
import netrc
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from base64 import b64encode
from collections import defaultdict
from datetime import date
from pathlib import Path

SERVER = "https://cnrbox.cnr.it/owncloud"
SYNC_ROOT = Path.home() / "cnrbox"  # local folder synced with the root of the account
LOCAL_DIR = SYNC_ROOT / "software" / "expo_packages"
OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "download.md"
SHARE_NAME = "EXPO download"

# Ubuntu codenames used in the names of the .deb packages
UBUNTU = {
    "jammy": "Ubuntu 22.04 LTS (Jammy Jellyfish)",
    "noble": "Ubuntu 24.04 LTS (Noble Numbat)",
    "plucky": "Ubuntu 25.04 (Plucky Puffin)",
    "questing": "Ubuntu 25.10 (Questing Quokka)",
    "resolute": "Ubuntu 26.04 LTS (Resolute Raccoon)",
}

PLATFORMS = ["Windows", "macOS", "Linux", "Docker", "Other"]

HEADER = """\
# Download

EXPO is distributed **free of charge** for academic, scientific, educational,
non-commercial and not-for-profit use. Commercial users are required to pay a license
fee. For information about the distribution of EXPO, please contact
[caterina.chiarella@ic.cnr.it](mailto:caterina.chiarella@ic.cnr.it).

After downloading, follow the [installation instructions](installation.md) for your
operating system.

<!-- This page is generated by scripts/make_download_page.py: do not edit it by hand. -->
"""


# --------------------------------------------------------------------------- HTTP

class Client:
    def __init__(self, server):
        self.server = server.rstrip("/")
        host = urllib.parse.urlparse(self.server).hostname
        try:
            auth = netrc.netrc().authenticators(host)
        except (FileNotFoundError, netrc.NetrcParseError) as exc:
            sys.exit(f"Cannot read ~/.netrc: {exc}")
        if not auth:
            sys.exit(f"No entry for '{host}' in ~/.netrc")
        token = b64encode(f"{auth[0]}:{auth[2]}".encode()).decode()
        self.headers = {"Authorization": f"Basic {token}", "OCS-APIRequest": "true"}

    def request(self, method, path, data=None, headers=None):
        url = self.server + path
        body = urllib.parse.urlencode(data).encode() if data else None
        req = urllib.request.Request(url, data=body, method=method,
                                     headers={**self.headers, **(headers or {})})
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return resp.status, resp.read()
        except urllib.error.HTTPError as exc:
            return exc.code, exc.read()

    def ocs(self, method, endpoint, params=None, data=None):
        query = urllib.parse.urlencode({**(params or {}), "format": "json"})
        status, body = self.request(method, f"/ocs/v1.php/{endpoint}?{query}", data)
        if status == 401:
            sys.exit("Authentication failed: check the username and app password in ~/.netrc")
        try:
            ocs = json.loads(body)["ocs"]
        except (ValueError, KeyError):
            sys.exit(f"Unexpected answer from {endpoint} (HTTP {status})")
        return ocs["meta"]["statuscode"], ocs["meta"].get("message"), ocs["data"]

    def user_id(self):
        code, msg, data = self.ocs("GET", "cloud/user")
        if code != 100:
            sys.exit(f"Cannot get user information: {msg}")
        return data["id"]

    def remote_sizes(self, user_id, remote_dir):
        """Return {file name: size} of the files in a remote folder (WebDAV)."""
        path = f"/remote.php/dav/files/{urllib.parse.quote(user_id)}{urllib.parse.quote(remote_dir)}/"
        status, body = self.request("PROPFIND", path, headers={"Depth": "1"})
        if status == 404:
            return {}
        if status != 207:
            sys.exit(f"Cannot list remote folder {remote_dir} (HTTP {status})")
        ns = {"d": "DAV:"}
        sizes = {}
        for resp in ET.fromstring(body).findall("d:response", ns):
            name = urllib.parse.unquote(resp.findtext("d:href", "", ns).rstrip("/").rsplit("/", 1)[-1])
            size = resp.findtext(".//d:getcontentlength", None, ns)
            if size is not None:
                sizes[name] = int(size)
        return sizes

    def public_link(self, remote_path, create):
        """Return the URL of a read-only public link of remote_path (None if missing)."""
        endpoint = "apps/files_sharing/api/v1/shares"
        code, msg, data = self.ocs("GET", endpoint, params={"path": remote_path})
        if code not in (100, 404):
            sys.exit(f"Cannot read shares of {remote_path}: {msg}")
        for share in data or []:
            if (int(share["share_type"]) == 3 and not share.get("share_with")
                    and not share.get("expiration") and int(share["permissions"]) == 1):
                return share["url"]
        if not create:
            return None
        code, msg, data = self.ocs("POST", endpoint, data={
            "path": remote_path, "shareType": 3, "permissions": 1, "name": SHARE_NAME})
        if code != 100:
            sys.exit(f"Cannot create a public link for {remote_path}: {msg}")
        return data["url"]


# --------------------------------------------------------------------- packages

PACKAGE_RE = re.compile(r"^expo2?-(?P<version>\d+(?:\.\d+)+)-(?P<tag>.+?)\.(?P<ext>exe|dmg|deb|tar\.gz|zip)$")


def describe(name):
    """Return (version, platform, description) for a package file name."""
    m = PACKAGE_RE.match(name)
    if not m:
        return None, "Other", ""
    version, tag, ext = m["version"], m["tag"], m["ext"]
    if ext == "exe":
        return version, "Windows", "Installer for 64-bit Windows 10 and 11"
    if ext == "dmg":
        arch = {"arm64": " (Apple Silicon)", "x86_64": " (Intel)"}.get(tag, "")
        return version, "macOS", f"Disk image for macOS{arch}"
    if ext == "deb":
        codename = tag.split("_")[0]
        return version, "Linux", f"Debian package for {UBUNTU.get(codename, codename)}"
    if tag == "docker":
        return version, "Docker", "Docker image"
    if tag == "Source":
        return version, "Linux", "Source code (CMake)"
    return version, "Other", ""


def version_key(version):
    return tuple(int(x) for x in version.split(".")) if version else ()


def human_size(size):
    return f"{size / 1024**2:.1f} MB" if size >= 1024**2 else f"{size / 1024:.0f} kB"


# ------------------------------------------------------------------------- page

def table(packages, indent=""):
    lines = ["| File | Description | Size | Date |",
             "|------|-------------|------|------|"]
    for p in sorted(packages, key=lambda p: p["name"]):
        link = f"[{p['name']}]({p['url']})" if p["url"] else f"{p['name']} *(link not created)*"
        lines.append(f"| {link} | {p['description']} | {p['size']} | {p['date']} |")
    return [indent + line for line in lines]


def version_section(packages, heading, indent=""):
    by_platform = defaultdict(list)
    for p in packages:
        by_platform[p["platform"]].append(p)
    lines = []
    for platform in PLATFORMS:
        if platform in by_platform:
            lines += [indent + f"{heading} {platform}", ""] + table(by_platform[platform], indent) + [""]
    return lines


def render(packages):
    by_version = defaultdict(list)
    for p in packages:
        by_version[p["version"]].append(p)
    versions = sorted(by_version, key=version_key, reverse=True)
    latest, older = versions[0], versions[1:]

    lines = [HEADER, f"## Latest version: {latest}", ""]
    lines += version_section(by_version[latest], "###")
    if older:
        lines += ["## Previous versions", "",
                  "Previous versions are considered obsolete, but they remain available for download.", ""]
        for v in older:
            lines += [f'??? note "Version {v or "unknown"}"', ""]
            lines += version_section(by_version[v], "####", indent="    ")
    return "\n".join(lines).rstrip() + "\n"


# ------------------------------------------------------------------------- main

def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dry-run", action="store_true", help="do not create public links")
    parser.add_argument("--local-dir", type=Path, default=LOCAL_DIR)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    local_dir = args.local_dir.expanduser().resolve()
    try:
        remote_dir = "/" + local_dir.relative_to(SYNC_ROOT.resolve()).as_posix()
    except ValueError:
        sys.exit(f"{local_dir} is not inside the synced folder {SYNC_ROOT}")
    files = sorted(f for f in local_dir.iterdir() if f.is_file() and not f.name.startswith("."))
    if not files:
        sys.exit(f"No files in {local_dir}")

    client = Client(SERVER)
    remote = client.remote_sizes(client.user_id(), remote_dir)

    packages, problems = [], 0
    for f in files:
        stat = f.stat()
        if remote.get(f.name) != stat.st_size:
            state = "not on the server yet" if f.name not in remote else "upload not complete"
            print(f"SKIP  {f.name}: {state} (wait for the sync client and run again)")
            problems += 1
            continue
        version, platform, description = describe(f.name)
        if platform == "Other":
            print(f"WARN  {f.name}: unknown file name pattern, listed under 'Other'")
        url = client.public_link(f"{remote_dir}/{f.name}", create=not args.dry_run)
        print(f"{'OK  ' if url else 'TODO'}  {f.name}  {url or '(link would be created)'}")
        packages.append({
            "name": f.name, "version": version, "platform": platform,
            "description": description, "size": human_size(stat.st_size),
            "date": date.fromtimestamp(stat.st_mtime).isoformat(),
            # '/download' gives a direct download instead of the ownCloud preview page
            "url": url + "/download" if url else None,
        })

    if not packages:
        sys.exit("No package available: download page not written")
    args.output.write_text(render(packages), encoding="utf-8")
    print(f"\nWritten {args.output} ({len(packages)} files"
          + (f", {problems} skipped" if problems else "") + ")")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
